    private static X2ApiFamilySnapshot? Snapshot(IX2WorldData data, string table) => table switch
    {
        "X2Map" => data.Map, "X2World" => data.WorldApi, "X2Warp" => data.Warp,
        "X2House" => data.Housing, "X2Dominion" => data.Dominion,
        "X2Resident" => data.Resident, "X2Indun" => data.Indun, "X2BattleField" => data.BattleField,
        "X2Instance" => data.InstanceData, "X2SiegeWeapon" => data.SiegeWeapon,
        "X2Decal" => data.Decal, "X2Interaction" => data.Interaction, _ => null
    };

    private static X2ApiResult? Find(X2ApiFamilySnapshot family, string method, LuaArgs args)
    {
        if (args.Count > 0)
        {
            var exact = method + "|" + string.Join("|", args.Values.Select(v => v switch
            {
                null => "", double d => d.ToString(CultureInfo.InvariantCulture), bool b => b ? "true" : "false",
                _ => v.ToString() ?? ""
            }));
            if (family.Results.TryGetValue(exact, out var result)) return result;
        }
        return family.Results.TryGetValue(method, out var fallback) ? fallback : null;
    }

    private static object? ToLuaResult(X2ApiResult result) => result.Multiple is { } values
        ? new LuaMulti(values.Select(ToLuaValue).ToArray())
        : ToLuaValue(result.Single);

    private static LuaTable ToLua(X2ApiTable value)
    {
        var table = new LuaTable();
        foreach (var (key, item) in value.Fields) table[key] = ToLuaValue(item);
        if (value.Rows is { } rows)
        {
            double index = 1;
            foreach (var item in rows) table[index++] = ToLuaValue(item);
        }
        return table;
    }

    private static object? ToLuaValue(object? value) => value switch
    {
        X2ApiTable table => ToLua(table),
        IEnumerable<X2ApiTable> tables => Array(tables.Select(ToLua)),
        IEnumerable<object?> values when value is not string => Array(values.Select(ToLuaValue)),
        _ => value
    };

    private static long ParseTime(object? value) => value switch
    {
        double d => (long)d,
        string s when long.TryParse(s, NumberStyles.Integer, CultureInfo.InvariantCulture, out var n) => n,
        LuaTable t when t.TryGetValue("year", out var y) => FromDate(t, y),
        _ => 0
    };

    private static long FromDate(LuaTable t, object? year) => new DateTimeOffset(
        Convert.ToInt32(year, CultureInfo.InvariantCulture), GetInt(t, "month", 1), GetInt(t, "day", 1),
        GetInt(t, "hour"), GetInt(t, "minute"), GetInt(t, "second"), TimeSpan.Zero).ToUnixTimeSeconds();
    private static int GetInt(LuaTable t, string key, int fallback = 0) =>
        t.TryGetValue(key, out var v) ? Convert.ToInt32(v, CultureInfo.InvariantCulture) : fallback;
    private static long Epoch(DateTimeOffset value) => value.ToUnixTimeSeconds();
    private static LuaTable Date(DateTimeOffset d) => new()
    {
        ["year"] = (double)d.Year, ["month"] = (double)d.Month, ["day"] = (double)d.Day,
        ["hour"] = (double)d.Hour, ["minute"] = (double)d.Minute, ["second"] = (double)d.Second,
        ["dayOfWeek"] = (double)d.DayOfWeek
    };
    private static LuaTable Period(double seconds)
    {
        seconds = Math.Max(0, seconds);
        var days = Math.Floor(seconds / 86400); seconds -= days * 86400;
        var hours = Math.Floor(seconds / 3600); seconds -= hours * 3600;
        var minutes = Math.Floor(seconds / 60); seconds -= minutes * 60;

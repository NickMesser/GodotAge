        name.StartsWith("Start", StringComparison.Ordinal) || name.StartsWith("Use", StringComparison.Ordinal) ||
        name.StartsWith("Change", StringComparison.Ordinal) || name.StartsWith("Fire", StringComparison.Ordinal) ||
        name.StartsWith("Refresh", StringComparison.Ordinal) || name.StartsWith("Ask", StringComparison.Ordinal) ||

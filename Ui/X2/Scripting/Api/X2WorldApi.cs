/// <summary>
/// Registers the World-family methods from the 10.0.2.13 generated API metadata.
/// X2World methods owned by X2Engine are deliberately retained because they carry the active login/world-selection session.
/// </summary>
public static class X2WorldApi
{
    private readonly record struct Binding(string Name, char Kind);

    public static void Install(X2LuaHost host, X2GameContext context, IX2WorldData data)
    {
        ArgumentNullException.ThrowIfNull(host);
        ArgumentNullException.ThrowIfNull(context);
        ArgumentNullException.ThrowIfNull(data);

        foreach (var (table, bindings) in All)
            foreach (var binding in bindings)
            {
                if (table == "X2World" && EngineOwnedWorldMethods.Contains(binding.Name))
                    continue;
                var capturedTable = table;
                var captured = binding;
                host.Define(capturedTable, captured.Name,
                    args => Invoke(capturedTable, captured, args, context, data));
            }
    }

    private static object? Invoke(string table, Binding binding, LuaArgs a, X2GameContext context, IX2WorldData data)
    {
        var key = table + "." + binding.Name;
        if (Snapshot(data, table) is { } family && Find(family, binding.Name, a) is { } capturedResult)
            return ToLuaResult(capturedResult);
        switch (key)
        {
            case "X2Time.GetUiMsec": return (double)data.UiMilliseconds;
            case "X2Time.GetLocalTime": return Epoch(data.LocalTime).ToString(CultureInfo.InvariantCulture);
            case "X2Time.GetLocalDate": return Date(data.LocalTime);
            case "X2Time.GetServerTime": return Date(data.ServerTime);
            case "X2Time.GetGameTime":
                var h24 = ((data.GameHour % 24) + 24) % 24;
                return new LuaMulti(h24 < 12, h24 < 12 ? Math.Floor(h24) : Math.Floor(h24) - 12, (h24 % 1) * 60);
            case "X2Time.CompareTime":
                var l = ParseTime(a[0]); var r = ParseTime(a[1]);
                return l == r ? 0d : l < r ? -1d : 1d;
            case "X2Time.TimeToDate": return Date(DateTimeOffset.FromUnixTimeSeconds(ParseTime(a[0])).ToLocalTime());
            case "X2Time.PeriodToDate": return Period(a.Num(0));
            case "X2Time.PeriodTimeToDate": return Period(ParseTime(a[1]) - ParseTime(a[0]));
            case "X2Time.DateToTimeString":
                return new DateTimeOffset(a.Int(0), Math.Clamp(a.Int(1), 1, 12), Math.Clamp(a.Int(2), 1, 28),
                    Math.Clamp(a.Int(3), 0, 23), Math.Clamp(a.Int(4), 0, 59), Math.Clamp(a.Int(5), 0, 59), TimeSpan.Zero)
                    .ToUnixTimeSeconds().ToString(CultureInfo.InvariantCulture);

            case "X2World.GetAuthId": return (double)data.World.AuthId;
            case "X2World.GetCurrentWorldName": return data.World.WorldName;
            case "X2World.GetCurrentWorldInfo": return WorldEntry(data.World);
            case "X2World.GetWorldInfo": return Array(data.World.WorldId == 0 ? [] : [WorldEntry(data.World)]);
            case "X2World.GetCharactersInfoPerWorld": return new LuaTable();
            case "X2World.GetCharactersCountPerWorld": return a.Int(0) == data.World.WorldId ? (double)data.World.CharacterCount : 0d;
            case "X2World.GetCharactersCountPerAccount": return (double)data.World.CharacterCount;
            case "X2World.GetCharactersDefaultLimitPerWorld": return (double)data.World.DefaultCharactersPerWorld;
            case "X2World.GetCharactersDefaultLimitPerAccount": return (double)data.World.DefaultCharactersPerAccount;
            case "X2World.GetCharacterExpandableLimit": return (double)data.World.ExpandableCharacters;
            case "X2World.GetExpandedCharacterCount": return (double)data.World.ExpandedCharacters;
            case "X2World.GetExpandedCharacterRemainCount": return (double)Math.Max(0, data.World.ExpandableCharacters - data.World.ExpandedCharacters);
            case "X2World.GetRemainChracterCountPerAccout": return (double)Math.Max(0, data.World.DefaultCharactersPerAccount - data.World.CharacterCount);
            case "X2World.GetZoneCount": return (double)data.World.Zones.Count;
            case "X2World.GetZoneInfo": return ZoneAt(data.World.Zones, a.Int(0));
            case "X2World.GetZoneName": return ZoneAt(data.World.Zones, a.Int(0))?["name"] ?? "";
            case "X2World.GetZoneText": return data.World.ZoneName;
            case "X2World.GetSubZoneText": return data.World.ZoneId != 0 && string.IsNullOrEmpty(data.World.SubZoneName)
                ? null : data.World.SubZoneName;
            case "X2World.GetZoneFaction": return data.World.ZoneFaction;
            case "X2World.IsWorld": return a.Int(0) == data.World.WorldId;
            case "X2World.IsDivision": return false;
            case "X2World.IsUsingAutoLogin":
            case "X2World.IsPreSelectCharacterPeriod":
            case "X2World.IsPreSelectCharacterPeriodForPcbang":
            case "X2World.IsPreSelectCharacterPeriodForPremium":
            case "X2World.ForbidCharCreation":
            case "X2World.CanPreSelectCharacter":
            case "X2World.IsB2PService": return false;
            case "X2World.LevelCount": return 0d;
            case "X2World.LevelName": return "";

            case "X2Map.GetZoneListByWorldId":
                return Array(data.World.Zones.Where(z => z.WorldId == 0 || z.WorldId == a.Int(0)).Select(ZoneEntry));
            case "X2Map.GetZoneStateInfoByZoneId":
                // the scripts pass X2Unit:GetCurrentZoneGroup() (a zones.group_id); our zone list is keyed by zone key
                var zoneId = a.Int(0) == 0 ? data.World.ZoneId : a.Int(0);
                var zone = data.World.Zones.FirstOrDefault(z => z.Id == zoneId) ??
                    (zoneId != 0 && zoneId == data.World.ZoneGroupId ? data.World.Zones.FirstOrDefault(z => z.Id == data.World.ZoneId) : null);
                return zone is null ? null : ZoneState(zone, zone.Id == data.World.ZoneId);
            case "X2Map.GetZoneStateTextInfo": return new LuaTable { ["stateTitle"] = "", ["tooltipTitle"] = "" };
            case "X2Map.GetCheckList": return Array(Online.X2MapIconCatalog.CheckList(a.Int(0)).Select(i => (object?)(double)i));
            case "X2Map.GetMapIconText": return Online.X2MapIconCatalog.IconText(a.Int(0));
            case "X2Map.GetMapIconCoord": return Online.X2MapIconCatalog.IconCoord(a.Int(0));
            case "X2Map.IsCheckedMapFilter": return Online.X2MapIconCatalog.IsChecked(a.Int(0));
            case "X2Map.GetZoneFactionCompetitionRemainTime": return 0d;

            case "X2Warp.GetPortalList": return PortalArray(Filter(data.Portals, a.Str(0), a.Int(1)));
            case "X2Warp.GetFavoritePortalList": return PortalArray(Filter(data.Portals.Where(p => p.Favorite), a.Str(0), a.Int(1)));
            case "X2Warp.GetReturnList": return PortalArray(Filter(data.ReturnPoints, a.Str(0), a.Int(1)));
            case "X2Warp.GetIndunPortalList": return PortalArray(Filter(data.InstancePortals, a.Str(0), 0));
            case "X2Warp.GetFavoritePortalCountInfos":
                return new LuaMulti((double)data.Portals.Count(p => p.Favorite), (double)data.Portals.Count);
            case "X2Warp.GetBoundPortalId": return data.ReturnPoints.FirstOrDefault()?.Id.ToString(CultureInfo.InvariantCulture) ?? "";

            case "X2House.GetHouseId": return (double)(data.CurrentHouse?.Id ?? 0);
            case "X2House.GetHouseType": return (double)(data.CurrentHouse?.Type ?? 0);
            case "X2House.GetHouseName": return data.CurrentHouse?.Name ?? "";
            case "X2House.GetHouseOwnerName": return data.CurrentHouse?.OwnerName ?? "";
            case "X2House.GetHouseZoneName": return data.CurrentHouse?.ZoneName ?? "";
            case "X2House.IsMyHouse": return data.CurrentHouse?.IsMine ?? false;
            case "X2House.IsHouseUnderConstruction": return data.CurrentHouse?.UnderConstruction ?? false;
            case "X2House.IsHouseRotatable": return data.CurrentHouse?.Rotatable ?? false;
            case "X2House.GetHousePermission": return (double)(data.CurrentHouse?.Permission ?? 0);
            case "X2House.GetHouseBaseProgress": return data.CurrentHouse?.BaseProgress ?? 0;
            case "X2House.GetHouseRemainProgress": return data.CurrentHouse?.RemainingProgress ?? 0;
            case "X2House.GetHouseAllowRecover": return data.CurrentHouse?.AllowRecover ?? false;

            case "X2Indun.IsEntranceIndunMatch":
            case "X2BattleField.IsInInstantGame": return data.CurrentInstance?.IsInInstantGame ?? false;
            case "X2BattleField.IsInGlobalField": return data.CurrentInstance?.IsGlobalField ?? false;
            case "X2Indun.GetTotalRound": return (double)(data.CurrentInstance?.TotalRounds ?? 0);
            case "X2Indun.GetRoundLeftTime": return data.CurrentInstance?.RoundSecondsLeft ?? 0;
            case "X2Indun.GetIndunPlayingInfo": return data.CurrentInstance is { } inst ? Instance(inst) : null;
            case "X2Indun.GetRoundInfo": return data.CurrentInstance is { } round ? new LuaTable { ["currentRound"] = (double)round.Round } : null;
            case "X2BattleField.GetInstanceName": return data.CurrentInstance?.Name ?? "";
            case "X2BattleField.GetProgressTimeInfo": return data.CurrentInstance is { } progress ? ProgressTime(progress) : null;
            case "X2Instance.GetInstanceSummaryInfo": return data.CurrentInstance is { } summary
                ? new LuaTable { ["type"] = (double)summary.InstanceType, ["isStarted"] = summary.ProgressState == "STARTED" }
                : null;
            case "X2Instance.GetPointInfo": return data.CurrentInstance is { } points ? PointArray(points.PointInfo ?? []) : null;

            case "X2SiegeWeapon.GetSiegeWeaponSpeed": return data.CurrentVehicle?.Speed ?? 0;
            case "X2SiegeWeapon.GetSiegeWeaponTurnSpeed": return data.CurrentVehicle?.TurnSpeed ?? 0;
            case "X2SiegeWeapon.GetSlaveCustomizingType": return (double)(data.CurrentVehicle?.CustomizingType ?? 0);
            case "X2SiegeWeapon.IsSlaveShip": return data.CurrentVehicle?.IsShip ?? false;
            case "X2SiegeWeapon.GetVehicleInfo": return data.CurrentVehicle is { IsShip: false } v ? Vehicle(v) : null;
            case "X2SiegeWeapon.GetShipInfo": return data.CurrentVehicle is { IsShip: true } ship ? Vehicle(ship) : null;
            case "X2SiegeWeapon.GetMountedSiegeWeaponInfo": return data.CurrentVehicle is { } mounted ? Vehicle(mounted) : null;
            case "X2Interaction.GetInteractionSkillIconPath": return data.InteractionSkillIconPath;
            case "X2Decal.GetMaxDecalCount": return 11d;
            // The quest notifier gates its navigation icon and distance behind these checks.
            // A positive quest type denotes an active quest supplied by its journal list.
            case "X2Decal.CanMakeDirectionGuide":
            case "X2Decal.CanMakeGuidedDecal": return a.Num(0) > 0;
        }

        if (IsCommand(binding.Name))
        {
            if (table == "X2Map" && binding.Name == "SetMapFilter")
            {
                Online.X2MapIconCatalog.SetChecked(a.Int(0), a.Bool(1));
                return null;
            }
            if (table == "X2Map" && binding.Name == "SetShowFilter")
            {
                Online.X2MapIconCatalog.SetFolder(a.Int(0), a.Bool(1));
                return null;
            }
            var result = data.Execute(new X2WorldCommand(table, binding.Name, a.Values.ToArray()));
            return binding.Kind switch { 'b' => result.Accepted, 'n' => result.Number, 's' => result.Text, _ => null };
        }

        // Empty state matches unavailable features on a fresh character and keeps optional windows closed.
        return binding.Kind switch { 'n' => 0d, 'b' => false, 's' => "", 't' => new LuaTable(), _ => null };
    }

    private static bool IsCommand(string name) => name.StartsWith("Set", StringComparison.Ordinal) ||

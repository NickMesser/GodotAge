/// <summary>
/// A recursively typed API table. Values may be null, string, bool, a numeric primitive, another X2ApiTable,
/// or a read-only list of those values. Field names are the exact keys consumed by x2ui.
/// </summary>
public sealed record X2ApiTable(IReadOnlyDictionary<string, object?> Fields, IReadOnlyList<object?>? Rows = null)
{
    public static X2ApiTable Empty { get; } = new(new Dictionary<string, object?>());
}

/// <summary>
/// One native API result. <see cref="Single"/> may be a primitive, X2ApiTable, or read-only list.
/// <see cref="Multiple"/> preserves ordered Lua multiple returns and takes precedence when non-null.
/// </summary>
public sealed record X2ApiResult(object? Single = null, IReadOnlyList<object?>? Multiple = null)
{
    public static X2ApiResult Scalar(object? value) => new(value);
    public static X2ApiResult Table(X2ApiTable value) => new(value);
    public static X2ApiResult Multi(params object?[] values) => new(null, values);
}

/// <summary>
/// Table results for one API family. Keys are a method name, or method plus invariant arguments separated by '|'
/// (for example "GetZoneStateInfoByZoneId|123"). This preserves argument-specific server snapshots.
/// </summary>
public sealed record X2ApiFamilySnapshot(IReadOnlyDictionary<string, X2ApiResult> Results)
{
    public static X2ApiFamilySnapshot Empty { get; } = new(new Dictionary<string, X2ApiResult>());
}

/// <summary>A command generated by a Lua API call. Arguments retain Lua's one-based indices and primitive values.</summary>
public sealed record X2WorldCommand(string Table, string Method, IReadOnlyList<object?> Arguments);

/// <summary>Synchronous result for commands whose native binding reports acceptance or a numeric status.</summary>
public sealed record X2WorldCommandResult(bool Accepted = false, double Number = 0, string Text = "");

/// <summary>
/// Live state and requests required by map, world, portal, time, housing, dominion, resident,
/// instance, battlefield, siege-weapon, decal, and interaction APIs.
/// </summary>
public interface IX2WorldData
{
    X2WorldState World { get; }
    DateTimeOffset ServerTime { get; }
    DateTimeOffset LocalTime { get; }
    /// <summary>Monotonic UI time in milliseconds.</summary>
    long UiMilliseconds { get; }
    /// <summary>ArcheAge world clock, in hours [0,24).</summary>
    double GameHour { get; }
    IReadOnlyList<X2PortalInfo> Portals { get; }
    IReadOnlyList<X2PortalInfo> ReturnPoints { get; }
    IReadOnlyList<X2PortalInfo> InstancePortals { get; }
    X2HouseInfo? CurrentHouse { get; }
    X2InstanceState? CurrentInstance { get; }
    X2VehicleState? CurrentVehicle { get; }
    /// <summary>Map checklists, alarms, zone state, and faction competition tables.</summary>
    X2ApiFamilySnapshot Map { get; }
    /// <summary>Non-login X2World service, terms, zone, and account query results.</summary>
    X2ApiFamilySnapshot WorldApi { get; }
    /// <summary>Portal queries not represented by the strongly typed portal lists.</summary>
    X2ApiFamilySnapshot Warp { get; }
    /// <summary>Housing tax, construction, sale, UCC, rebuilding, and item tables.</summary>
    X2ApiFamilySnapshot Housing { get; }
    /// <summary>Dominion ownership, siege periods, scores, rewards, and timer tables.</summary>
    X2ApiFamilySnapshot Dominion { get; }
    /// <summary>Resident board, member, zone, reward, and housing-trade tables.</summary>
    X2ApiFamilySnapshot Resident { get; }
    /// <summary>Dungeon round, playing, and entrance tables.</summary>
    X2ApiFamilySnapshot Indun { get; }
    /// <summary>Battlefield entrance, progress, score, faction, member, reward, and banner tables.</summary>
    X2ApiFamilySnapshot BattleField { get; }
    /// <summary>Instance summary and faction-point tables.</summary>
    X2ApiFamilySnapshot InstanceData { get; }
    /// <summary>Mounted weapon, vehicle, ship, and equipment-slot tables.</summary>
    X2ApiFamilySnapshot SiegeWeapon { get; }
    /// <summary>Quest guide and target-decal capability query results.</summary>
    X2ApiFamilySnapshot Decal { get; }
    /// <summary>NPC interaction query results.</summary>
    X2ApiFamilySnapshot Interaction { get; }
    string InteractionSkillIconPath { get; }
    /// <summary>Forwards a server request or renderer-side command. State changes only after host/network confirmation.</summary>
    X2WorldCommandResult Execute(X2WorldCommand command);
}


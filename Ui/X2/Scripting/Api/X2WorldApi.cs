/// <summary>Immutable state used by the world-facing x2ui API families.</summary>
public sealed record X2WorldState
{
    public int WorldId { get; init; }
    public string WorldName { get; init; } = "";
    public int AuthId { get; init; }
    public int CharacterCount { get; init; }
    public int DefaultCharactersPerWorld { get; init; } = 6;
    public int DefaultCharactersPerAccount { get; init; } = 12;
    public int ExpandableCharacters { get; init; }
    public int ExpandedCharacters { get; init; }
    public int ZoneId { get; init; }
    /// <summary>zones.group_id of the current zone (X2Unit:GetCurrentZoneGroup; 0 when unknown).</summary>
